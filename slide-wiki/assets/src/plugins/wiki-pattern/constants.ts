/**
 * 左（本文）と右（図解）の幅の比。
 *
 * **左幅は `1行 全角26字`（ontology.yaml の guidance）から決まる。**
 * 版面 9.12in のうち 20/33 ＝ 5.53in が左段、本文の箱はそこから内側の余白を引いて 5.33in。
 * 全角1字の送りは 14pt に対して 0.194in（1em）が下限で、この環境の実測は 1.02em。
 * **1.05em で見て 26字 ＝ 5.31in** が入る幅にしてある。
 *
 * **1字が 0.2in、そのまま図の幅。** 左段の使い残しは本文と図の間の余白として
 * そのまま見えるので（行は箱の右端まで届かない）、規約を1字増やすことと
 * 図を 0.2in 細くすることは同じ操作になる。25字なら 7:5（左 5.32in・図 3.80in）、
 * 27字なら 12:7（左 5.76in・図 3.36in）。26字はその間で、配布中の176行を実測すると
 * 最長の行が箱の 89%（25字では 96%、27字では 85%）— 折り返しまでの余裕がいちばん釣り合う。
 *
 * 字幅が 1.05em を超えるフォントで読まれると 26字の行が折り返し、
 * 見積り（`countVisualLines` は 1em で数える）と1行ずれる。
 */
export const WP_LEFT_RATIO = 20
export const WP_RIGHT_RATIO = 13

/**
 * 左カラムの余白。**コアの SECTION_GAP / HEADING_BODY_GAP より詰めてある。**
 *
 * このレイアウトは1枚に必ず2つの見出しと3つ前後の段落が入る（`いつ・なにが困るか` は
 * 場面と困りごとの2段落に割れ、段落は見出しの無い節として積まれる）。既定の余白のままだと
 * 左カラムの高さ 3.9in の半分以上が余白で消え、本文に 1.4in しか残らない。そうなると
 * 全ページが `dispatchLayout` の縮小に入り、**本文の長さに応じてページごとに文字が
 * 小さくなる** ＝ Wiki として並べたときに揃わない。余白を詰めて縮小そのものを起こさせない。
 *
 * この値で固定費は 1.14in（余白 0.20 + 節間 0.15×2 + 見出し 0.26×2 + 見出し-本文 0.06×2）、
 * 本文に残るのは 2.76in。見出しが3つだった頃は固定費 1.46in で本文 2.44in だったので、
 * **1見出しぶん減らして本文が 14pt で約1行ぶん増えている**。
 *
 * コアの定数を書き換えないのは、9つ以上のレイアウトが共有しているため
 * （触れば既存のデッキが黙って組み変わる）。
 */
export const WP_SECTION_GAP = 0.15
export const WP_HEADING_HEIGHT = 0.26
export const WP_HEADING_BODY_GAP = 0.06

